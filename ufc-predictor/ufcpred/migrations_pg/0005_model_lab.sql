-- Model Lab: one row per graded official prediction with each alternative model's chance for the red corner.
-- Tracking only: rebuilt from predictions/results/odds; nothing in the prediction engine reads it.
CREATE TABLE IF NOT EXISTS model_lab (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id    BIGINT NOT NULL UNIQUE REFERENCES predictions(id),
    fight_id         BIGINT NOT NULL REFERENCES fights(id),
    event_id         BIGINT NOT NULL REFERENCES events(id),
    mode             TEXT NOT NULL,
    event_date       TEXT,
    weight_class     TEXT,
    is_women         INTEGER,
    card_segment     TEXT,
    scheduled_rounds INTEGER,
    result_id        BIGINT,
    red_won          INTEGER NOT NULL,
    p_engine         DOUBLE PRECISION,
    p_ratings        DOUBLE PRECISION,
    p_form           DOUBLE PRECISION,
    p_style          DOUBLE PRECISION,
    p_durability     DOUBLE PRECISION,
    p_elo            DOUBLE PRECISION,
    market_red       DOUBLE PRECISION,
    red_decimal      DOUBLE PRECISION,
    blue_decimal     DOUBLE PRECISION,
    created_at       TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_model_lab_mode ON model_lab(mode);
