CREATE TABLE IF NOT EXISTS audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts            TEXT NOT NULL,
    actor         TEXT NOT NULL,
    action        TEXT NOT NULL,
    entity        TEXT,
    entity_id     TEXT,
    details_json  TEXT
);

CREATE TABLE IF NOT EXISTS settings (
    key           TEXT PRIMARY KEY,
    value_json    TEXT NOT NULL,
    updated_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS job_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job           TEXT NOT NULL,
    started_at    TEXT NOT NULL,
    finished_at   TEXT,
    status        TEXT NOT NULL,
    message       TEXT
);

CREATE OR REPLACE FUNCTION ufcpred_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only: rows cannot be %d', TG_TABLE_NAME, lower(TG_OP);
END $$;
DROP TRIGGER IF EXISTS trg_predictions_append_only ON predictions;
CREATE TRIGGER trg_predictions_append_only BEFORE UPDATE OR DELETE ON predictions
    FOR EACH ROW EXECUTE FUNCTION ufcpred_append_only();
DROP TRIGGER IF EXISTS trg_prediction_locks_append_only ON prediction_locks;
CREATE TRIGGER trg_prediction_locks_append_only BEFORE UPDATE OR DELETE ON prediction_locks
    FOR EACH ROW EXECUTE FUNCTION ufcpred_append_only();
DROP TRIGGER IF EXISTS trg_promotion_decisions_append_only ON promotion_decisions;
CREATE TRIGGER trg_promotion_decisions_append_only BEFORE UPDATE OR DELETE ON promotion_decisions
    FOR EACH ROW EXECUTE FUNCTION ufcpred_append_only();
DROP TRIGGER IF EXISTS trg_audit_log_append_only ON audit_log;
CREATE TRIGGER trg_audit_log_append_only BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION ufcpred_append_only();
