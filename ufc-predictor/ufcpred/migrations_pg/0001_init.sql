-- Postgres translation of migrations/0001_init.sql (same tables, columns and guarantees).
-- Append-only tables are enforced by triggers that raise on UPDATE/DELETE.

CREATE TABLE IF NOT EXISTS data_sources (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider      TEXT NOT NULL,
    resource      TEXT NOT NULL,
    url           TEXT,
    license       TEXT,
    retrieved_at  TEXT NOT NULL,
    sha256        TEXT,
    status        TEXT NOT NULL,              -- ok | error | stale | cached
    http_status   INTEGER,
    error         TEXT,
    cache_path    TEXT,
    rows          INTEGER
);
CREATE INDEX IF NOT EXISTS ix_data_sources_provider ON data_sources(provider, resource, retrieved_at);

CREATE TABLE IF NOT EXISTS fighters (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id   TEXT UNIQUE,                 -- e.g. ufcstats:93fe7332d16c6ad9
    name          TEXT NOT NULL,
    nickname      TEXT,
    dob           TEXT,                        -- ISO date or NULL (unknown)
    height_in     DOUBLE PRECISION,
    reach_in      DOUBLE PRECISION,
    stance        TEXT,
    listed_weight_lbs DOUBLE PRECISION,
    source_id BIGINT REFERENCES data_sources(id),
    origin        TEXT NOT NULL DEFAULT 'provider',   -- provider | manual
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_fighters_name ON fighters(name);

-- Manually verified corrections to fighter attributes. Applied on read; the original
-- provider value is never overwritten.
CREATE TABLE IF NOT EXISTS fighter_corrections (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fighter_id BIGINT NOT NULL REFERENCES fighters(id),
    field         TEXT NOT NULL,
    value         TEXT,
    source_url    TEXT,
    note          TEXT,
    created_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id   TEXT UNIQUE,
    name          TEXT NOT NULL,
    date          TEXT NOT NULL,               -- ISO date (local event date)
    start_time_utc TEXT,                       -- when known; otherwise lock uses date
    venue         TEXT,
    location      TEXT,
    status        TEXT NOT NULL DEFAULT 'scheduled', -- scheduled|locked|completed|evaluated|canceled|missed_lock
    origin        TEXT NOT NULL DEFAULT 'provider',  -- provider | manual
    source_id BIGINT REFERENCES data_sources(id),
    source_url    TEXT,
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_events_date ON events(date);

CREATE TABLE IF NOT EXISTS fights (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id   TEXT UNIQUE,
    event_id BIGINT NOT NULL REFERENCES events(id),
    red_fighter_id BIGINT NOT NULL REFERENCES fighters(id),
    blue_fighter_id BIGINT NOT NULL REFERENCES fighters(id),
    weight_class  TEXT,
    is_title      INTEGER NOT NULL DEFAULT 0,
    is_women      INTEGER NOT NULL DEFAULT 0,
    scheduled_rounds INTEGER,
    time_format   TEXT,
    card_segment  TEXT NOT NULL DEFAULT 'unknown',   -- main | prelim | early_prelim | unknown
    bout_order    INTEGER,                         -- 1 = main event
    status        TEXT NOT NULL DEFAULT 'scheduled', -- scheduled|completed|canceled|replaced
    replaced_by_fight_id BIGINT REFERENCES fights(id) DEFERRABLE INITIALLY DEFERRED,
    short_notice_red  INTEGER,                     -- NULL = unknown, 0/1 = documented
    short_notice_blue INTEGER,
    weight_miss_red   INTEGER,
    weight_miss_blue  INTEGER,
    origin        TEXT NOT NULL DEFAULT 'provider',
    source_id BIGINT REFERENCES data_sources(id),
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL,
    CHECK (red_fighter_id <> blue_fighter_id)
);
CREATE INDEX IF NOT EXISTS ix_fights_event ON fights(event_id);
CREATE INDEX IF NOT EXISTS ix_fights_red ON fights(red_fighter_id);
CREATE INDEX IF NOT EXISTS ix_fights_blue ON fights(blue_fighter_id);

-- Official results, revisioned. The latest revision is authoritative; older ones are kept.
CREATE TABLE IF NOT EXISTS fight_results (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fight_id BIGINT NOT NULL REFERENCES fights(id),
    revision      INTEGER NOT NULL,
    outcome       TEXT NOT NULL,              -- win | draw | nc
    winner_fighter_id BIGINT REFERENCES fighters(id),
    method        TEXT,                       -- KO_TKO | SUB | DEC | DQ | OTHER | NC | DRAW
    method_detail TEXT,
    end_round     INTEGER,
    end_time_sec  INTEGER,
    total_time_sec INTEGER,
    referee       TEXT,
    details       TEXT,
    reason        TEXT,                       -- why this revision exists
    origin        TEXT NOT NULL DEFAULT 'provider',
    source_id BIGINT REFERENCES data_sources(id),
    source_url    TEXT,
    recorded_at   TEXT NOT NULL,
    UNIQUE (fight_id, revision)
);
CREATE INDEX IF NOT EXISTS ix_results_fight ON fight_results(fight_id, revision);

CREATE TABLE IF NOT EXISTS fight_stats (
    fight_id BIGINT NOT NULL REFERENCES fights(id),
    fighter_id BIGINT NOT NULL REFERENCES fighters(id),
    round         INTEGER NOT NULL,
    kd INTEGER, sig_l INTEGER, sig_a INTEGER, tot_l INTEGER, tot_a INTEGER,
    td_l INTEGER, td_a INTEGER, sub_att INTEGER, rev INTEGER, ctrl_sec INTEGER,
    head_l INTEGER, head_a INTEGER, body_l INTEGER, body_a INTEGER, leg_l INTEGER, leg_a INTEGER,
    dist_l INTEGER, dist_a INTEGER, clinch_l INTEGER, clinch_a INTEGER, ground_l INTEGER, ground_a INTEGER,
    PRIMARY KEY (fight_id, fighter_id, round)
);

-- Point-in-time fighter snapshots: exactly what the engine knew about a fighter before
-- a given fight. Written when a prediction is made and referenced from the ledger.
CREATE TABLE IF NOT EXISTS fighter_snapshots (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fighter_id BIGINT NOT NULL REFERENCES fighters(id),
    fight_id BIGINT REFERENCES fights(id),
    as_of         TEXT NOT NULL,
    state_json    TEXT NOT NULL,
    sha256        TEXT NOT NULL,
    created_at    TEXT NOT NULL,
    UNIQUE (fighter_id, fight_id, sha256)
);

CREATE TABLE IF NOT EXISTS odds (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fight_id BIGINT NOT NULL REFERENCES fights(id),
    provider      TEXT NOT NULL,
    bookmaker     TEXT,
    red_decimal   DOUBLE PRECISION NOT NULL,
    blue_decimal  DOUBLE PRECISION NOT NULL,
    captured_at   TEXT NOT NULL,
    source_url    TEXT,
    created_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_odds_fight ON odds(fight_id, captured_at);

CREATE TABLE IF NOT EXISTS model_versions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label         TEXT NOT NULL UNIQUE,
    parent_id BIGINT REFERENCES model_versions(id),
    status        TEXT NOT NULL,              -- candidate | active | retired | rejected
    config_json   TEXT NOT NULL,
    params_json   TEXT NOT NULL,
    params_sha256 TEXT NOT NULL,
    training_cutoff TEXT NOT NULL,            -- only fights strictly before this date were used
    n_train       INTEGER NOT NULL,
    training_run_id INTEGER,
    notes         TEXT,
    created_at    TEXT NOT NULL,
    activated_at  TEXT
);

CREATE TABLE IF NOT EXISTS training_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at    TEXT NOT NULL,
    finished_at   TEXT,
    cutoff        TEXT NOT NULL,
    n_train       INTEGER,
    config_json   TEXT NOT NULL,
    diagnostics_json TEXT,
    seed          INTEGER,
    status        TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS backtest_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label         TEXT NOT NULL,
    config_json   TEXT NOT NULL,
    config_sha256 TEXT NOT NULL,
    start_date    TEXT,
    end_date      TEXT,
    n_folds       INTEGER,
    n_fights      INTEGER,
    metrics_json  TEXT,
    folds_json    TEXT,
    leakage_audit_json TEXT,
    created_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS backtest_predictions (
    backtest_run_id BIGINT NOT NULL REFERENCES backtest_runs(id),
    fight_id BIGINT NOT NULL REFERENCES fights(id),
    event_id      INTEGER NOT NULL,
    fold          INTEGER NOT NULL,
    train_cutoff  TEXT NOT NULL,
    p_red         DOUBLE PRECISION NOT NULL,
    red_won       INTEGER NOT NULL,
    method_probs_json TEXT,
    actual_method TEXT,
    PRIMARY KEY (backtest_run_id, fight_id)
);

-- The prediction ledger. Append-only (see triggers below).
CREATE TABLE IF NOT EXISTS predictions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fight_id BIGINT NOT NULL REFERENCES fights(id),
    event_id BIGINT NOT NULL REFERENCES events(id),
    version       INTEGER NOT NULL,
    supersedes_id BIGINT REFERENCES predictions(id),
    reason        TEXT NOT NULL,
    mode          TEXT NOT NULL,              -- live | replay
    created_at    TEXT NOT NULL,              -- wall-clock time the row was written
    as_of         TEXT NOT NULL,              -- decision time: data after this is invisible
    data_cutoff   TEXT NOT NULL,              -- latest fight date the features could see (exclusive)
    model_version_id BIGINT NOT NULL REFERENCES model_versions(id),
    red_fighter_id  INTEGER NOT NULL,
    blue_fighter_id INTEGER NOT NULL,
    red_snapshot_id BIGINT REFERENCES fighter_snapshots(id),
    blue_snapshot_id BIGINT REFERENCES fighter_snapshots(id),
    p_red         DOUBLE PRECISION NOT NULL,
    p_blue        DOUBLE PRECISION NOT NULL,
    predicted_winner_id INTEGER NOT NULL,
    predicted_method TEXT NOT NULL,
    predicted_round INTEGER,
    confidence    TEXT NOT NULL,
    is_post_lock  INTEGER NOT NULL DEFAULT 0,
    payload_json  TEXT NOT NULL,              -- full probabilities, contributions, explanation, quality, params
    content_sha256 TEXT NOT NULL,
    prev_sha256   TEXT,                       -- hash chain over the whole ledger
    UNIQUE (fight_id, version, mode)
);
CREATE INDEX IF NOT EXISTS ix_predictions_event ON predictions(event_id, mode);
CREATE INDEX IF NOT EXISTS ix_predictions_fight ON predictions(fight_id, mode, version);


CREATE TABLE IF NOT EXISTS prediction_locks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    mode          TEXT NOT NULL,
    locked_at     TEXT NOT NULL,
    as_of         TEXT NOT NULL,
    reason        TEXT NOT NULL,
    prediction_ids_json TEXT NOT NULL,
    UNIQUE (event_id, mode)
);

CREATE TABLE IF NOT EXISTS prediction_evaluations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id BIGINT NOT NULL REFERENCES predictions(id),
    result_id BIGINT NOT NULL REFERENCES fight_results(id),
    evaluated_at  TEXT NOT NULL,
    scored        INTEGER NOT NULL,           -- 0 for draws/NC/canceled (excluded from winner metrics)
    correct_winner INTEGER,
    p_actual      DOUBLE PRECISION,
    brier         DOUBLE PRECISION,
    log_loss      DOUBLE PRECISION,
    method_correct INTEGER,
    round_correct INTEGER,
    method_log_loss DOUBLE PRECISION,
    calibration_note TEXT,                    -- overconfident | underconfident | consistent
    details_json  TEXT NOT NULL,
    UNIQUE (prediction_id, result_id)
);

CREATE TABLE IF NOT EXISTS error_diagnostics (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id BIGINT NOT NULL REFERENCES prediction_evaluations(id),
    prediction_id BIGINT NOT NULL REFERENCES predictions(id),
    category      TEXT NOT NULL,              -- ordinary_uncertainty | data_quality | model_weakness
    report_json   TEXT NOT NULL,
    created_at    TEXT NOT NULL,
    UNIQUE (evaluation_id)
);

CREATE TABLE IF NOT EXISTS learning_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_event_id BIGINT REFERENCES events(id),
    mode          TEXT NOT NULL,
    as_of         TEXT NOT NULL,
    started_at    TEXT NOT NULL,
    finished_at   TEXT,
    status        TEXT NOT NULL,
    summary_json  TEXT
);

CREATE TABLE IF NOT EXISTS weakness_hypotheses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key           TEXT NOT NULL,
    learning_run_id BIGINT REFERENCES learning_runs(id),
    description   TEXT NOT NULL,
    n             INTEGER NOT NULL,
    effect        DOUBLE PRECISION,
    ci_low        DOUBLE PRECISION,
    ci_high       DOUBLE PRECISION,
    p_value       DOUBLE PRECISION,
    q_value       DOUBLE PRECISION,
    status        TEXT NOT NULL,              -- insufficient_data | not_supported | supported
    evidence_json TEXT,
    created_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_hyp_key ON weakness_hypotheses(key, created_at);

CREATE TABLE IF NOT EXISTS candidate_changes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learning_run_id BIGINT NOT NULL REFERENCES learning_runs(id),
    hypothesis_key TEXT,
    kind          TEXT NOT NULL,
    description   TEXT NOT NULL,
    config_json   TEXT NOT NULL,
    status        TEXT NOT NULL,              -- proposed | tested | promoted | rejected | pending_approval
    candidate_backtest_id BIGINT REFERENCES backtest_runs(id),
    incumbent_backtest_id BIGINT REFERENCES backtest_runs(id),
    result_json   TEXT,
    created_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS promotion_decisions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_change_id BIGINT REFERENCES candidate_changes(id),
    incumbent_version_id BIGINT REFERENCES model_versions(id),
    candidate_version_id BIGINT REFERENCES model_versions(id),
    decision      TEXT NOT NULL,              -- promote | reject | retain | refit | rollback | initial | pending_approval | approve
    criteria_json TEXT NOT NULL,
    reason        TEXT NOT NULL,
    decided_by    TEXT NOT NULL,              -- auto | manual
    decided_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS evaluation_metrics (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learning_run_id BIGINT REFERENCES learning_runs(id),
    scope         TEXT NOT NULL,
    scope_key     TEXT,
    metric        TEXT NOT NULL,
    value         DOUBLE PRECISION,
    n             INTEGER,
    ci_low        DOUBLE PRECISION,
    ci_high       DOUBLE PRECISION,
    computed_at   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS analyst_reports (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learning_run_id BIGINT REFERENCES learning_runs(id),
    event_id BIGINT REFERENCES events(id),
    provider      TEXT NOT NULL,              -- deterministic | anthropic
    structured_json TEXT NOT NULL,
    created_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS data_quality_issues (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity        TEXT NOT NULL,
    entity_id     TEXT,
    severity      TEXT NOT NULL,              -- info | warning | error
    kind          TEXT NOT NULL,
    message       TEXT NOT NULL,
    detected_at   TEXT NOT NULL,
    resolved_at   TEXT,
    UNIQUE (entity, entity_id, kind)
